/* Private functions ---------------------------------------------------------*/
void OLED_WriteCommand(uint8_t command) {
	uint8_t data[2] = {0x00, command}; // 0x00 = registre de contrôle pour commande
	HAL_StatusTypeDef status = HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDRESS, data, 2, HAL_MAX_DELAY);
	if (status != HAL_OK) {
		printf("I2C command error: %lu\r\n", HAL_I2C_GetError(&hi2c1));
	}
}

void OLED_WriteData(uint8_t* data, uint16_t size) {
	uint8_t buffer[size + 1];
	buffer[0] = 0x40; // 0x40 = registre de contrôle pour données
	memcpy(&buffer[1], data, size);
	HAL_StatusTypeDef status = HAL_I2C_Master_Transmit(&hi2c1, OLED_ADDRESS, buffer, size + 1, HAL_MAX_DELAY);
	if (status != HAL_OK) {
		printf("I2C data error: %lu\r\n", HAL_I2C_GetError(&hi2c1));
	}
}

/* Exported functions --------------------------------------------------------*/
void OLED_Init(void) {
	HAL_Delay(100); // Attendre que l'OLED soit prêt
	OLED_WriteCommand(0xAE); // Display OFF
	OLED_WriteCommand(OLED_SETDISPLAYCLOCKDIV); // Horloge
	OLED_WriteCommand(0x80);
	OLED_WriteCommand(OLED_SETMULTIPLEX); // Ratio multiplex
	OLED_WriteCommand(0x3F); // 64 lignes
	OLED_WriteCommand(OLED_SETDISPLAYOFFSET); // Offset
	OLED_WriteCommand(0x00);
	OLED_WriteCommand(OLED_SETSTARTLINE | 0x0); // Ligne de départ
	OLED_WriteCommand(OLED_ENABLECHARGEPUMP); // Activer pompe de charge
	OLED_WriteCommand(0x14);
	OLED_WriteCommand(OLED_SEGREMAP | 0x1); // Remap segment
	OLED_WriteCommand(OLED_COMSCANDEC); // Scan direction
	OLED_WriteCommand(OLED_SETCOMPINS); // Configuration des pins
	OLED_WriteCommand(0x12);
	OLED_WriteCommand(OLED_SETCONTRAST); // Contraste
	OLED_WriteCommand(0xCF);
	OLED_WriteCommand(OLED_SETPRECHARGE); // Précharge
	OLED_WriteCommand(0xF1);
	OLED_WriteCommand(OLED_SETVCOMDETECT); // VCOM
	OLED_WriteCommand(0x40);
	OLED_WriteCommand(OLED_NORMALDISPLAY); // Affichage normal
	OLED_WriteCommand(OLED_DISPLAYON); // Display ON
}

void OLED_Clear(void) {
	uint8_t clear_data[128] = {0x00}; // Buffer de 128 octets à 0
	for (uint8_t page = 0; page < 8; page++) { // 8 pages pour 64 lignes
		OLED_WriteCommand(0xB0 + page); // Sélectionner la page
		OLED_WriteCommand(0x00); // Colonne basse
		OLED_WriteCommand(0x10); // Colonne haute
		OLED_WriteData(clear_data, 128); // Écrire 128 octets
	}
}

void OLED_DisplayChar(char c, uint8_t page, uint8_t col) {
	uint8_t index = 0;
	if (c >= 'A' && c <= 'Z') {
		index = c - 'A'; // A-Z (0-25)
	} else if (c >= '0' && c <= '9') {
		index = (c - '0') + 26; // 0-9 (26-35)
	} else {
		return; // Caractère non supporté
	}
	OLED_WriteCommand(0xB0 + page); // Sélectionner la page
	OLED_WriteCommand(col & 0x0F); // Colonne basse
	OLED_WriteCommand(0x10 | (col >> 4)); // Colonne haute
	OLED_WriteData((uint8_t*)font_5x7[index], 5); // Afficher le caractère
}

void OLED_DisplayString(const char* str, uint8_t page, uint8_t col) {
	while (*str) {
		OLED_DisplayChar(*str, page, col);
		col += 6; // 5 pixels pour le caractère + 1 espace
		str++;
	}
}
void OLED_DisplayBitmap(void) {
	for (uint8_t page = 0; page < 8; page++) {
		OLED_WriteCommand(0xB0 + page); // Sélectionner la page
		OLED_WriteCommand(0x00); // Colonne basse
		OLED_WriteCommand(0x10); // Colonne haute
		OLED_WriteData((uint8_t*)&bitmap_data[page * 128], 128); // Écrire 128 octets
	}
}
